// C program to display different data types
#include <stdio.h>

int main() {
    int a = 5;             
    float b = 5.0;          
    char c = 'A';           
    double d = 12.3456;     

    
    printf("Integer value: %d\n", a);
    printf("Float value: %.2f\n", b);
    printf("Character value: %c\n", c);
    printf("Double value: %.4lf\n", d);

    return 0;
}
